TODAY = datetime.date(2026, 10, 11)
D = datetime.date.fromisoformat

GANTT_BOARD = [
    {"id": "R1", "title": "[0.1.0] First thing.", "status": "Done", "started": "2026-01-01", "completed": "2026-02-01"},
    {"id": "R2", "title": "[0.1.0] Second thing: with a colon; and #hash", "status": "Done", "started": "2026-01-01", "completed": "2026-02-01"},
    {"id": "R3", "title": "[0.1.1] Same-day release", "status": "Done", "started": "2026-03-01", "completed": "2026-03-01"},
    {"id": "R4", "title": "[0.1.2] Also same day", "status": "Done", "started": "2026-03-01", "completed": "2026-03-01"},
    {"id": "R5", "title": "[0.2.0] Later", "status": "Done", "started": "2026-03-01", "completed": "2026-04-15"},
    {"id": "O1", "title": "A finished draft", "status": "Done", "completed": "2026-03-01"},          # only Completed
    {"id": "P1", "title": "In flight", "status": "In Progress", "started": "2026-09-01"},
    {"id": "T1", "title": "Not started", "status": "Todo", "started": "2026-09-05"},                  # open work: no bar
    {"id": "U1", "title": "Undated done item", "status": "Done"},                                      # nothing to draw
]


def _tasks(view):
    return cli.gantt_tasks(GANTT_BOARD, view, mock.Mock(config_data={}), TODAY)


def test_gantt_tasks_per_release_merges_same_day_releases_and_adds_active_items():
    tasks, skipped = _tasks("releases")
    assert skipped == 2                                                       # the undated Done item and the Todo item
    rows = [(t["section"], t["name"], str(t["start"]), str(t["end"]), t["state"]) for t in tasks]
    assert rows == [
        ("Releases", "v0.1.0", "2026-01-01", "2026-02-01", "done"),
        ("Releases", "v0.1.1 to v0.1.2 (2 releases)", "2026-03-01", "2026-03-01", "done"),   # one bar for the same day
        ("Releases", "v0.2.0", "2026-03-01", "2026-04-15", "done"),
        ("In progress", "In flight", "2026-09-01", "2026-10-11", "active")]               # runs to today
    # the finished draft without a changelog entry only appears in the per-item view


def test_gantt_tasks_per_item_groups_by_release():
    tasks, skipped = _tasks("items")
    assert [(t["section"], t["name"]) for t in tasks] == [
        ("v0.1.0", "First thing."), ("v0.1.0", "Second thing: with a colon; and #hash"),
        ("v0.1.1", "Same-day release"), ("v0.1.2", "Also same day"), ("v0.2.0", "Later"),
        ("Other completed", "A finished draft"), ("In progress", "In flight")]
    other = next(t for t in tasks if t["name"] == "A finished draft")
    assert other["start"] == other["end"] == D("2026-03-01")                  # the missing Started borrows Completed


def test_gantt_tasks_respect_custom_field_names():
    board = [{"id": "X", "title": "Thing", "status": "Done", "kickoff": "2026-01-01", "shipped": "2026-01-09"}]
    args = mock.Mock(config_data={"dates": {"started": "Kickoff", "completed": "Shipped"}})
    tasks, skipped = cli.gantt_tasks(board, "items", args, TODAY)
    assert [(str(t["start"]), str(t["end"])) for t in tasks] == [("2026-01-01", "2026-01-09")] and skipped == 0


def test_render_mermaid_is_safe_and_uses_one_day_durations():
    tasks, _ = _tasks("items")
    text = cli.render_mermaid("kopi roadmap", tasks)
    lines = text.splitlines()
    assert lines[:4] == ["gantt", "    title kopi roadmap", "    dateFormat YYYY-MM-DD", "    axisFormat %b %Y"]
    assert "    section v0.1.0" in lines
    assert "    Second thing∶ with a colon#59; and #35;hash :done, 2026-01-01, 2026-02-01" in lines   # colon becomes U+2236; ; and # are entity-encoded
    assert "    Same-day release :done, 2026-03-01, 1d" in lines                    # a one-day bar needs a duration
    assert "    In flight :active, 2026-09-01, 2026-10-11" in lines
    long = cli.render_mermaid("t", [{"section": "S", "name": "x" * 200, "start": D("2026-01-01"), "end": D("2026-01-05"), "state": "done"}])
    assert "x" * 69 + "…" in long                                                  # long names are cut
    wide = [{"section": "S", "name": "n", "start": D("2013-01-01"), "end": D("2026-01-01"), "state": "done"}]
    assert "axisFormat %Y" in cli.render_mermaid("t", wide)


def test_render_svg_is_well_formed_and_carries_the_marker():
    tasks, _ = _tasks("items")
    svg = cli.render_svg('Roadmap <&> "quoted"', tasks, TODAY, "Generated by kopi gantt items from project #2 (me).")
    root = ET.fromstring(svg)                                                   # parses: no `--` in comments, text escaped
    assert root.tag.endswith("svg") and svg.splitlines()[0].startswith("<!-- Generated by kopi gantt")
    assert len(root.findall(".//{http://www.w3.org/2000/svg}rect[@class='d']")) == 6 and "Same-day release" in svg
    assert len(root.findall(".//{http://www.w3.org/2000/svg}rect[@class='a']")) == 1       # the in-progress bar
    assert "var(--" not in svg                                                  # plain colours: renders in any viewer
    assert "prefers-color-scheme:dark" in svg and 'class="td"' in svg           # dark-mode override, and today's marker
    # every bar lies inside the canvas
    for rect in root.iter("{http://www.w3.org/2000/svg}rect"):
        if rect.get("class") in ("d", "a"):
            assert 0 <= float(rect.get("x")) and float(rect.get("x")) + float(rect.get("width")) <= 1100


def test_render_gantt_picks_the_format_from_the_extension():
    tasks, _ = _tasks("releases")
    md = cli.render_gantt("ROADMAP.md", "kopi roadmap", tasks, "releases", 2, "me", TODAY)
    assert md.startswith("<!-- Generated by kopi gantt releases from project #2 (me).") and "```mermaid\ngantt\n" in md and md.endswith("```\n")
    mmd = cli.render_gantt("chart.mmd", "kopi roadmap", tasks, "releases", 2, "me", TODAY)
    assert mmd.startswith("%% Generated by kopi gantt") and "```" not in mmd and "gantt\n" in mmd
    assert cli.render_gantt("chart.SVG", "kopi roadmap", tasks, "releases", 2, "me", TODAY).lstrip().startswith("<!--")


def _gantt(tmp_path, monkeypatch, argv, items=GANTT_BOARD, **kw):
    monkeypatch.chdir(tmp_path)
    return _run_update(items, argv=argv, **kw)


def test_gantt_writes_roadmap_md_by_default_and_is_idempotent(tmp_path, monkeypatch, capsys):
    rc, rj, run = _gantt(tmp_path, monkeypatch, ("--gantt",))
    assert rc == 0 and f"4 bars written to {cli.GANTT_FILE}; 2 items without dates skipped" in capsys.readouterr().out
    text = (tmp_path / "ROADMAP.md").read_text()
    assert text.startswith("<!-- Generated by kopi gantt releases from project #2 (lateralblast).") and "# kopi roadmap" in text
    assert not run.called                                                       # read-only on GitHub
    _gantt(tmp_path, monkeypatch, ("--gantt", "releases"))
    assert "ROADMAP.md is up to date (4 bars)" in capsys.readouterr().out
    _gantt(tmp_path, monkeypatch, ("--gantt", "items"))
    assert "7 bars written" in capsys.readouterr().out and "section Other completed" in (tmp_path / "ROADMAP.md").read_text()


def test_gantt_to_svg_dry_run_stdout_and_json(tmp_path, monkeypatch, capsys):
    _gantt(tmp_path, monkeypatch, ("--gantt", "items", "--to", "road.svg"))
    ET.parse(tmp_path / "road.svg")                                             # a valid SVG file
    _gantt(tmp_path, monkeypatch, ("--gantt", "--to", "other.md", "--dry-run"))
    assert not (tmp_path / "other.md").exists() and "Dry run: 4 bars would be written to other.md" in capsys.readouterr().out
    _gantt(tmp_path, monkeypatch, ("--gantt", "--to", "-"))
    out = capsys.readouterr().out
    assert out.startswith("<!-- Generated by kopi gantt") and "gantt\n" in out and not (tmp_path / "-").exists()
    _gantt(tmp_path, monkeypatch, ("--json", "--gantt", "--to", "j.md"))
    data = json.loads(capsys.readouterr().out)
    assert data["view"] == "releases" and data["file"] == "j.md" and data["skipped"] == 2 and data["changed"] is True
    assert data["tasks"][0] == {"section": "Releases", "name": "v0.1.0", "start": "2026-01-01", "end": "2026-02-01", "state": "done"}


def test_gantt_protects_a_hand_written_file_and_needs_dates(tmp_path, monkeypatch, capsys):
    (tmp_path / "ROADMAP.md").write_text("# My own roadmap\n")
    rc, *_ = _gantt(tmp_path, monkeypatch, ("--gantt",))
    assert rc == 1 and "was not generated by kopi" in capsys.readouterr().err
    assert (tmp_path / "ROADMAP.md").read_text() == "# My own roadmap\n"
    rc, *_ = _gantt(tmp_path, monkeypatch, ("--gantt", "--force"))
    assert rc == 0 and (tmp_path / "ROADMAP.md").read_text().startswith("<!-- Generated by kopi gantt")
    rc, *_ = _gantt(tmp_path, monkeypatch, ("--gantt", "--to", "none.md"), items=[{"id": "U", "title": "Undated", "status": "Done"}])
    assert rc == 1 and "run --backfill-dates" in capsys.readouterr().err and not (tmp_path / "none.md").exists()
    with pytest.raises(SystemExit):
        cli.main(["--to", "x.md", "--update"])                                  # --to belongs to --gantt
    with pytest.raises(SystemExit):
        cli.main(["--gantt", "--update"])
    with pytest.raises(SystemExit):
        cli.main(["--gantt", "bogus"])


def test_releases_view_draws_one_bar_per_version_when_all_releases_fall_on_two_days():
    board = [{"id": f"V{i}", "title": f"[0.0.{i}] Thing {i}", "status": "Done", "started": day, "completed": day}
             for i, day in enumerate(["2026-10-09"] * 5 + ["2026-10-11"] * 2, 1)]
    tasks, _ = cli.gantt_tasks(board, "releases", mock.Mock(config_data={}), TODAY)
    assert [t["name"] for t in tasks] == [f"v0.0.{i}" for i in range(1, 8)]
    assert _tasks("releases")[0][1]["name"] == "v0.1.1 to v0.1.2 (2 releases)"   # three release days: still grouped


